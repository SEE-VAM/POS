'',
'  var existing = cartItems.find(function(ci) { return ci.id === productId; });',
'  if (existing) {',
'    existing.qty += 1;',
'  } else {',
'    cartItems.push({',
'      id: prod.id,',
'      name: prod.name,',
'      price: prod.price,',
'      qty: 1',
'    });',
'  }',
'  renderCart();',
