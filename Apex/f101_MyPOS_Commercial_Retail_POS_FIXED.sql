'        ''<div style="font-weight:700; color:#475569; font-size:1rem; margin-bottom:4px;">Cart is empty</div>'' +',
'        ''<div style="font-size:0.8rem; line-height:1.4;">Click any product card or scan barcode to add items</div>'' +',
'      ''</div>'';',
'    return;',
'  }',
'',
'  var html = '''';',
'  cartItems.forEach(function(ci) {',
'    var lineTotal = ci.price * ci.qty;',
'    html += ',
'      ''<div class="pos-cart-item-row">'' +',
'        ''<div class="pos-cart-item-name" title="'' + ci.name + ''">'' + ci.name + ''</div>'' +',
'        ''<div class="pos-cart-item-controls">'' +',
'          ''<button type="button" class="pos-qty-btn" onclick="updateCartQty('' + ci.id + '', -1)">-</button>'' +',
